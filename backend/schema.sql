CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY, name TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('worker','customer'))
);
CREATE TABLE IF NOT EXISTS workers (
 id INTEGER PRIMARY KEY REFERENCES users(id), trade TEXT NOT NULL, experienceYears INTEGER NOT NULL CHECK(experienceYears BETWEEN 0 AND 80),
 city TEXT NOT NULL, locality TEXT NOT NULL, price INTEGER CHECK(price > 0), seeded INTEGER NOT NULL DEFAULT 0,
 createdAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS skills (
 workerId INTEGER NOT NULL REFERENCES workers(id), name TEXT NOT NULL COLLATE NOCASE, PRIMARY KEY(workerId,name)
);
CREATE TABLE IF NOT EXISTS availability (
 workerId INTEGER PRIMARY KEY REFERENCES workers(id), accepting INTEGER NOT NULL CHECK(accepting IN (0,1))
);
CREATE TABLE IF NOT EXISTS service_requests (
 id INTEGER PRIMARY KEY, customerId INTEGER NOT NULL REFERENCES users(id), trade TEXT NOT NULL, problem TEXT NOT NULL,
 urgency TEXT NOT NULL, city TEXT NOT NULL, locality TEXT NOT NULL, seeded INTEGER NOT NULL DEFAULT 0, createdAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS bookings (
 id INTEGER PRIMARY KEY, requestId INTEGER NOT NULL REFERENCES service_requests(id), workerId INTEGER NOT NULL REFERENCES workers(id),
 description TEXT NOT NULL, price INTEGER NOT NULL CHECK(price > 0), startsAt TEXT NOT NULL, endsAt TEXT NOT NULL CHECK(endsAt > startsAt),
 location TEXT NOT NULL, status TEXT NOT NULL CHECK(status IN ('REQUESTED','NEGOTIATING','CONFIRMED','COMPLETED','CANCELLED','REJECTED')),
 proposedBy TEXT NOT NULL CHECK(proposedBy IN ('worker','customer')), version INTEGER NOT NULL DEFAULT 1, seeded INTEGER NOT NULL DEFAULT 0,
 createdAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS bookings_calendar ON bookings(workerId,status,startsAt,endsAt);
CREATE TABLE IF NOT EXISTS messages (
 id INTEGER PRIMARY KEY, bookingId INTEGER NOT NULL REFERENCES bookings(id), senderId INTEGER NOT NULL REFERENCES users(id),
 body TEXT NOT NULL, createdAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS reviews (
 bookingId INTEGER PRIMARY KEY REFERENCES bookings(id), rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),
 feedback TEXT NOT NULL, createdAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS work_evidence (
 bookingId INTEGER PRIMARY KEY REFERENCES bookings(id), mime TEXT NOT NULL, photo BLOB NOT NULL,
 createdAt TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
